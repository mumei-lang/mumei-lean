"""Render the generated CLI reference."""

from __future__ import annotations

import argparse
import importlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPTS_DIR = REPO_ROOT / "scripts"
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

CLI_SCRIPTS = (
    ("scripts/bridge.py", "bridge"),
    ("scripts/check_authorization_model.py", "check_authorization_model"),
    ("scripts/export_cert.py", "export_cert"),
    ("scripts/ingest_cert.py", "ingest_cert"),
    ("scripts/lean_to_executable.py", "lean_to_executable"),
    ("scripts/sync_contract_constants.py", "sync_contract_constants"),
)

ENVIRONMENT_VARIABLES = (
    (
        "MUMEI_REPO",
        "../mumei",
        "Used by sync_contract_constants.py when --mumei-repo is omitted; "
        "the sibling checkout is the fallback.",
    ),
    (
        "MUMEI_AGENT_REPO",
        "../mumei-agent",
        "Used by sync_contract_constants.py when --mumei-agent-repo is omitted; "
        "the sibling checkout is the fallback.",
    ),
)

INTERNAL_ENV_ALLOWLIST = {}


def markdown_cell(value: object | None) -> str:
    if value is None:
        return "—"
    collapsed = " ".join(str(value).split())
    if not collapsed:
        return "—"
    return collapsed.replace("|", r"\|")


def _visible_actions(
    parser: argparse.ArgumentParser,
    *,
    positional: bool,
) -> list[argparse.Action]:
    return [
        action
        for action in parser._actions
        if bool(action.option_strings) != positional
        and action.help != argparse.SUPPRESS
        and not isinstance(action, argparse._HelpAction)
    ]


def _value_label(action: argparse.Action) -> str:
    if action.choices is not None:
        choices = action.choices
        if isinstance(choices, (set, frozenset)):
            choices = sorted(choices, key=str)
        return "{" + ", ".join(str(choice) for choice in choices) + "}"
    if action.nargs == 0:
        return "—"
    metavar = action.metavar
    if isinstance(metavar, tuple):
        return " ".join(f"<{part}>" for part in metavar)
    value = str(metavar or action.dest.upper())
    label = f"<{value}>"
    if action.nargs == argparse.OPTIONAL:
        return f"[{label}]"
    if action.nargs == argparse.ZERO_OR_MORE:
        return f"[{label} ...]"
    if action.nargs in {argparse.ONE_OR_MORE, argparse.REMAINDER}:
        return f"{label} ..."
    return label


def _markdown_value_label(action: argparse.Action) -> str:
    value = _value_label(action)
    return "—" if value == "—" else f"`{markdown_cell(value)}`"


def _default_label(action: argparse.Action) -> str:
    default = action.default
    if default is None or default == argparse.SUPPRESS:
        return "—"
    if isinstance(action, argparse._StoreTrueAction) and default is False:
        return "—"
    if isinstance(default, Path):
        if default.is_absolute():
            try:
                return default.relative_to(REPO_ROOT).as_posix() or "."
            except ValueError:
                return "<absolute path>"
        return default.as_posix()
    if isinstance(default, str) and Path(default).is_absolute():
        try:
            return Path(default).relative_to(REPO_ROOT).as_posix() or "."
        except ValueError:
            return "<absolute path>"
    return str(default)


def _help_text(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    if not action.help:
        return "—"
    return parser._get_formatter()._expand_help(action)


def capture_parsers() -> list[tuple[str, argparse.ArgumentParser]]:
    references = []
    for script_path, module_name in CLI_SCRIPTS:
        module = importlib.import_module(module_name)
        references.append((script_path, module.build_parser()))
    return references


def render_cli_reference() -> str:
    references = capture_parsers()
    lines = [
        "<!-- Generated by `./scripts/gen_cli_reference.py`; do not edit by hand. -->",
        "",
        "# CLI Reference",
        "",
        "Generated from the argparse definitions in the repository's user-facing scripts.",
        "",
        "## Environment variables",
        "",
        "| Variable | Default fallback | Description |",
        "|---|---|---|",
    ]
    for name, default, description in ENVIRONMENT_VARIABLES:
        lines.append(
            f"| `{name}` | `{markdown_cell(default)}` | {markdown_cell(description)} |"
        )
    lines.extend(
        [
            "",
            "An explicit command-line repository path takes precedence over its environment variable.",
            "",
            "| Script | Option count | Description |",
            "|---|---:|---|",
        ]
    )
    for script_path, parser in references:
        options = _visible_actions(parser, positional=False)
        lines.append(
            f"| `{script_path}` | {len(options)} | "
            f"{markdown_cell(parser.description or '')} |"
        )
    for script_path, parser in references:
        lines.extend(["", f"## `{script_path}`", ""])
        if parser.description:
            lines.extend([markdown_cell(parser.description), ""])
        groups = [
            group
            for group in parser._mutually_exclusive_groups
            if any(action.option_strings for action in group._group_actions)
        ]
        if groups:
            lines.extend(
                [
                    "### Mutually exclusive groups",
                    "",
                    "| Options | Required |",
                    "|---|---|",
                ]
            )
            for group in groups:
                options = ", ".join(
                    f"`{markdown_cell(option)}`"
                    for action in group._group_actions
                    for option in action.option_strings
                )
                lines.append(f"| {options} | {'yes' if group.required else 'no'} |")
            lines.append("")
        positionals = _visible_actions(parser, positional=True)
        if positionals:
            lines.extend(
                [
                    "### Positional arguments",
                    "",
                    "| Argument | Value | Required | Default | Description |",
                    "|---|---|---|---|---|",
                ]
            )
            for action in positionals:
                lines.append(
                    f"| `{markdown_cell(action.dest)}` | "
                    f"{_markdown_value_label(action)} | "
                    f"{'yes' if action.required else 'no'} | "
                    f"{markdown_cell(_default_label(action))} | "
                    f"{markdown_cell(_help_text(parser, action))} |"
                )
            lines.append("")
        options = _visible_actions(parser, positional=False)
        if options:
            lines.extend(
                [
                    "### Options",
                    "",
                    "| Option | Value | Required | Default | Description |",
                    "|---|---|---|---|---|",
                ]
            )
            for action in options:
                option = ", ".join(action.option_strings)
                lines.append(
                    f"| `{markdown_cell(option)}` | "
                    f"{_markdown_value_label(action)} | "
                    f"{'yes' if action.required else 'no'} | "
                    f"{markdown_cell(_default_label(action))} | "
                    f"{markdown_cell(_help_text(parser, action))} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"
